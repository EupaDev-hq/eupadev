// Generates the Claude Code check of the agent image's CI:
// `images/agent/check/claude.sh` (the engine's EXACT command line, CLAUDE_LINE),
// `images/agent/check/report.schema.json` (the report schema as the engine passes it, schemaDraft07) and
// `images/agent/managed-settings.json` (managed settings copied into /etc/claude-code/ of the image: forbidden paths of
// `forbidden-paths.ts`, the same list as the launcher).
// A single source: the engine; a test fails if the files no longer match.
// Usage: node scripts/generate-claude-check.ts
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { budgetClaude, CLAUDE_LINE, roleOptions, schemaDraft07 } from '../src/external/claude-engine.ts';
import { managedDenyRules } from '../src/agent-engine/forbidden-paths.ts';

export const DIR = new URL('../../images/agent/check/', import.meta.url);
export const IMAGE_DIR = new URL('../../images/agent/', import.meta.url);
const SCHEMA = new URL('../../tool-template/agents/report.schema.json', import.meta.url);

/**
 * Claude Code managed settings in the agent image (`/etc/claude-code/managed-settings.json`, root, 0644, read-only
 * root filesystem: the agent cannot change them; settings doc "managed settings take precedence"). A belt behind
 * the launcher: hooks forbidden, bypassPermissions forbidden, forbidden paths refused to Edit/Write, Read of the task
 * allowed, no project CLAUDE.md or MCP server, non-essential traffic cut. No
 * `blockReadsOutsideWorkingDirectories` (A-R4, ADR-020): under `--restricted`, the read-only Bash set already does not read
 * outside the working directories, and the setting also refuses the ALLOWED Bash of the code roles outside those directories
 * (trial against the fake upstream on 2026-10-18, Claude Code 2.1.287).
 */
export function managedSettings(): string {
  return `${JSON.stringify({
    allowManagedHooksOnly: true,
    disableAllHooks: true,
    allowManagedPermissionRulesOnly: false,
    permissions: { disableBypassPermissionsMode: 'disable', allow: ['Read(//tmp/task/**)'], deny: managedDenyRules() },
    enableAllProjectMcpServers: false,
    env: { CLAUDE_CODE_DISABLE_CLAUDE_MDS: '1', DISABLE_AUTOUPDATER: '1', DISABLE_UPDATES: '1', CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC: '1' },
  }, null, 2)}\n`;
}

export function generateCheck(): { 'claude.sh': string; 'report.schema.json': string } {
  const { tools: tools, permissions } = roleOptions('builder');
  const script = `#!/bin/sh
# GENERATED by orchestrator/scripts/generate-claude-check.ts (npm run generate): do not edit by hand.
# Runs Claude Code with the engine's exact command line (claude-engine.ts), WITHOUT network (free).
# Accepted: it gets past the start (waits for the network until the timeout, code 124, or returns a JSON "result" message).
# Refused: it stops before, with an error text (unknown option, setting that requires a package, schema refused...).
# Inputs: /tmp/task/report.schema.json; writable HOME.
set -u
export FA_PROMPT='Answer "ok".' FA_MODEL='claude-haiku-5-5' FA_EFFORT='low' FA_TOOLS='${tools}' FA_PERMISSIONS='${permissions}'
export FA_TURNS='10' FA_BUDGET='${budgetClaude(1)}'
mkdir -p /tmp/output && echo 'Instructions of the check.' > /tmp/task/instructions.md || exit 2
cd "$HOME" && git init -q repo && cd repo || exit 2
timeout 30 ${CLAUDE_LINE} \\
  </dev/null >/tmp/output/result.json 2>/tmp/output/errors.txt
code=$?
if [ "$code" = 124 ] || head -c 300 /tmp/output/result.json | grep -q '"type": *"result"'; then
  echo "OK: Claude Code accepts the engine's options and report schema (code $code)"
  exit 0
fi
echo "FAILED: Claude Code refuses the engine's options or report schema (code $code):"
tail -c 2000 /tmp/output/errors.txt
tail -c 2000 /tmp/output/result.json
exit 1
`;
  return { 'claude.sh': script, 'report.schema.json': `${JSON.stringify(JSON.parse(schemaDraft07(readFileSync(SCHEMA, 'utf8'))), null, 2)}\n` };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(DIR, { recursive: true });
  for (const [name, text] of Object.entries(generateCheck())) writeFileSync(new URL(name, DIR), text);
  writeFileSync(new URL('managed-settings.json', IMAGE_DIR), managedSettings());
  console.log(`images/agent/check/: ${Object.keys(generateCheck()).join(', ')}; images/agent/managed-settings.json`);
}
