// Generates, from src/machine/states.ts, the mermaid diagram and the list of "to be
// confirmed" choices of MACHINE.md, between the markers <!-- generated:start --> and <!-- generated:end -->.
// Usage: node scripts/generate-mermaid.ts [MACHINE.md]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { STATES, INITIAL_STATE, TRANSITIONS, triggerKey, type Kind } from '../src/machine/states.ts';

const START = '<!-- generated:start -->';
const END = '<!-- generated:end -->';

const PHASE_LABEL: Record<string, string> = {
  entry: 'Entry', scoping: 'Scoping', contract: 'Contract', hardening: 'Hardening', delivery: 'Delivery', cross_cutting: 'Cross-cutting', end: 'Ends',
};

export function generateMermaid(): string {
  const l: string[] = ['stateDiagram-v2', '  direction TB'];
  for (const n of ['active', 'waiting', 'gate', 'end'] as const satisfies readonly Kind[]) {
    const ids = STATES.filter((e) => e.kind === n).map((e) => e.id);
    if (ids.length > 0) l.push(`  class ${ids.join(', ')} kind_${n}`);
  }
  l.push('  classDef kind_waiting fill:#fff3bf,stroke:#b08900', '  classDef kind_gate fill:#ffd8d8,stroke:#b00020', '  classDef kind_end fill:#d3f9d8,stroke:#2b8a3e', '  classDef kind_active fill:#e7f0ff,stroke:#1c4f9c');
  l.push(`  [*] --> ${INITIAL_STATE}`);
  for (const [phase, label] of Object.entries(PHASE_LABEL)) {
    const states = STATES.filter((e) => e.phase === phase);
    if (states.length === 0) continue;
    l.push(`  state "${label}" as phase_${phase} {`);
    for (const e of states) l.push(`    ${e.id}`);
    l.push('  }');
  }
  for (const t of TRANSITIONS) {
    if (t.trigger.type === 'cancellation' || t.trigger.type === 'incident' || t.trigger.type === 'resume') continue; // one arrow per state is unreadable: see the note under the diagram
    const suffix = t.bound === undefined ? '' : ` (×${t.bound})`;
    l.push(`  ${t.from} --> ${t.to} : ${triggerKey(t.trigger)}${suffix}`);
  }
  for (const e of STATES.filter((e) => e.kind === 'end')) l.push(`  ${e.id} --> [*]`);
  return l.join('\n');
}

export function generateBlock(): string {
  const cancellationCount = TRANSITIONS.filter((t) => t.trigger.type === 'cancellation').length;
  const incidentCount = TRANSITIONS.filter((t) => t.trigger.type === 'incident').length;
  const byKind = (n: Kind) => STATES.filter((e) => e.kind === n).length;
  return [
    START,
    `_Generated by \`scripts/generate-mermaid.ts\` from \`src/machine/states.ts\` — ${STATES.length} states (${byKind('active')} active, ${byKind('waiting')} waiting, ${byKind('gate')} gates, ${byKind('end')} ends), ${TRANSITIONS.length} transitions, ${cancellationCount} of them cancellations._`,
    '',
    '```mermaid',
    generateMermaid(),
    '```',
    '',
    `Not drawn, to stay readable: \`cancellation\` from each of the ${cancellationCount} non-final states to \`end_cancellation\` (E15); \`incident\` from each of the ${incidentCount} other non-final states to \`gate_incident\`, and \`resume:<state>\` from \`gate_incident\` to each of them (D21, back to the original state only, checked by the database). The \`(×N)\` arrows are bounded repeats in place.`,
    END,
  ].join('\n');
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  const path = process.argv[2] ?? 'MACHINE.md';
  const content = readFileSync(path, 'utf8');
  const start = content.indexOf(START);
  const end = content.indexOf(END);
  if (start < 0 || end < start) throw new Error(`${path}: markers ${START} / ${END} not found`);
  writeFileSync(path, content.slice(0, start) + generateBlock() + content.slice(end + END.length));
  console.log(`${path}: diagram regenerated (${STATES.length} states, ${TRANSITIONS.length} transitions)`);
}
