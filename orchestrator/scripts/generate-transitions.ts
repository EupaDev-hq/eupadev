// Generates the SQL migration that projects `states` and `allowed_transitions` from
// src/machine/states.ts. Never edit the produced file by hand.
// Usage: node scripts/generate-transitions.ts migrations/NNNN_state-machine.sql
// A migration already applied is never modified (ADR-004): if the machine changes, use a
// NEW number (tests/machine.test.ts compares the latest `*_state-machine.sql` with the generation).
// The migration is an upsert: cycles, tasks and history reference `states` (foreign keys), so the
// table cannot be emptied (0002 did it: empty database). A row removed from the machine is deleted;
// if it is still referenced, PostgreSQL refuses and the migration fails: fail-closed.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { STATES, TRANSITIONS, triggerKey } from '../src/machine/states.ts';

const sql = (s: string) => `'${s.replaceAll("'", "''")}'`;

export function generateSql(): string {
  const lines: string[] = [
    '-- Up Migration',
    '-- GENERATED by scripts/generate-transitions.ts from src/machine/states.ts — do not edit.',
    `-- ${STATES.length} states, ${TRANSITIONS.length} transitions.`,
    'INSERT INTO states (id, phase, kind, description) VALUES',
    ...STATES.map((e, i) => `  (${sql(e.id)}, ${sql(e.phase)}, ${sql(e.kind)}, ${sql(e.description)})${i === STATES.length - 1 ? '' : ','}`),
    'ON CONFLICT (id) DO UPDATE SET phase = EXCLUDED.phase, kind = EXCLUDED.kind, description = EXCLUDED.description;',
    `DELETE FROM allowed_transitions WHERE (from_state, trigger) NOT IN (${TRANSITIONS.map((t) => `(${sql(t.from)}, ${sql(triggerKey(t.trigger))})`).join(', ')});`,
    'INSERT INTO allowed_transitions (from_state, trigger, to_state, note) VALUES',
    ...TRANSITIONS.map((t, i) => `  (${sql(t.from)}, ${sql(triggerKey(t.trigger))}, ${sql(t.to)}, ${sql(t.note)})${i === TRANSITIONS.length - 1 ? '' : ','}`),
    'ON CONFLICT (from_state, trigger) DO UPDATE SET to_state = EXCLUDED.to_state, note = EXCLUDED.note;',
    `DELETE FROM states WHERE id NOT IN (${STATES.map((e) => sql(e.id)).join(', ')});`,
    '',
    '-- Down Migration',
    '-- Nothing to undo: the previous projection stays applied (0002 and the following ones); the descriptions are prose.',
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  const path = process.argv[2];
  if (path === undefined || !/^migrations\/\d{4}_state-machine\.sql$/.test(path)) {
    console.error('usage: node scripts/generate-transitions.ts migrations/NNNN_state-machine.sql (a NEW number: an applied migration is never modified)');
    process.exit(2);
  }
  writeFileSync(path, generateSql());
  console.log(`${path}: ${STATES.length} states, ${TRANSITIONS.length} transitions`);
}
