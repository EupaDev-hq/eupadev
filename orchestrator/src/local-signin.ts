/**
 * Local sign-in of the discovery mode (ADR-028): a tiny OIDC issuer derived from the test helper `tests/helpers/fake-oidc.ts`,
 * run as one container of `infra/compose/discovery/compose.yml`, on the loopback address only. It serves Keycloak's layout
 * under one realm (the path of `OIDC_ISSUER`): `/protocol/openid-connect/auth` (a sign-in form), `token` (authorization
 * code + PKCE S256, `client_secret_post`), `certs` (JWKS) and `logout`, and issues the access token the engine already
 * verifies (ES256, `typ at+jwt`, `aud`, `resource_access.<audience>.roles`, `email`, `name`). The engine does not change:
 * it reads the same `OIDC_*` variables as with Keycloak, and this process reads them too.
 *
 * Two accounts, `requester` and `admin`, one hat each (the four-eyes rule of Gate 2 needs two people). Their passwords are
 * generated by `install.sh`, shown once on the installer's terminal (ADR-028) and handed over as `SIGNIN_REQUESTER_PASSWORD`
 * and `SIGNIN_ADMIN_PASSWORD` (or `_FILE`): this process keeps scrypt hashes in memory, writes nothing and never logs
 * a password. Keys are generated at every start: the engine keeps its own session after the callback.
 *
 * Usage (the Compose file): node src/local-signin.ts, with OIDC_ISSUER, OIDC_WEB_CLIENT_ID, OIDC_WEB_CLIENT_SECRET (or
 * _FILE), OIDC_WEB_REDIRECT_URL, OIDC_AUDIENCE (eupadev-api), API_ADDRESS, API_PORT, SIGNIN_REQUESTER_PASSWORD and
 * SIGNIN_ADMIN_PASSWORD (or _FILE).
 *
 * ponytail: no rate limit on the form and no login cookie — the issuer answers on 127.0.0.1 of one machine, to two people.
 */
import { createHash, randomBytes, scryptSync, timingSafeEqual } from 'node:crypto';
import http from 'node:http';
import { once } from 'node:events';
import type { AddressInfo } from 'node:net';
import { exportJWK, generateKeyPair, SignJWT, type JWK } from 'jose';
import type { Hat } from './auth.ts';
import { LOOPBACK_HOSTS, readSecret } from './config.ts';
import { text, type Language } from './i18n.ts';

export interface LocalSignInOptions {
  /** Public issuer, as the browser and the engine's `OIDC_ISSUER` see it: `http://localhost:8081/realms/eupadev`. */
  issuer: string;
  /** The engine's confidential web client (ADR-024) and its registered redirect URL. */
  clientId: string;
  clientSecret: string;
  redirectUrl: string;
  /** `aud` of the access token and key of `resource_access` (default eupadev-api). */
  audience?: string;
  /** Password of each account of `ACCOUNTS`, from the installer (hashed in memory, never logged). */
  passwords: Readonly<Record<string, string>>;
  address?: string;
  port?: number;
  /** Lines for the container log (default `console.log`). */
  log?: (line: string) => void;
}

export interface LocalSignIn {
  /** `http://<address>:<port>` actually listened on. */
  url: string;
  jwksUrl: string;
  stop: () => Promise<void>;
}

/** The two accounts: one hat each. The subject is the account name (identity `(issuer, subject)`, ADR-017). */
export const ACCOUNTS: Readonly<Record<string, { name: string; roles: readonly Hat[] }>> = {
  requester: { name: 'Alex Martin', roles: ['requester'] },
  admin: { name: 'Sam Bernard', roles: ['admin'] },
};
/** Variable that carries the password of an account: `SIGNIN_REQUESTER_PASSWORD`, `SIGNIN_ADMIN_PASSWORD` (or `_FILE`). */
export const passwordVariable = (account: string): string => `SIGNIN_${account.toUpperCase()}_PASSWORD`;
const CODE_TTL_MS = 60_000;
const TOKEN_TTL_S = 300;

interface StoredAccount { salt: string; hash: string }
type Accounts = Record<string, StoredAccount>;

const hashPassword = (password: string, salt: string): string => scryptSync(password, salt, 32).toString('hex');

/** Hashes the installer's passwords (scrypt, random salt) so that the clear text lives nowhere in this process. */
function hashAccounts(passwords: Readonly<Record<string, string>>): Accounts {
  const accounts: Accounts = {};
  for (const name of Object.keys(ACCOUNTS)) {
    const password = passwords[name] ?? '';
    if (password.trim() === '') throw new Error(`${passwordVariable(name)} missing: the installer generates it and shows it once (ADR-028)`);
    const salt = randomBytes(16).toString('hex');
    accounts[name] = { salt, hash: hashPassword(password, salt) };
  }
  return accounts;
}

function checkPassword(accounts: Accounts, username: string, password: string): boolean {
  const stored = accounts[username];
  // Unknown account: hash anyway, so that a name cannot be guessed from the answer time.
  const expected = Buffer.from(stored?.hash ?? hashPassword('', 'unknown'), 'hex');
  return stored !== undefined && timingSafeEqual(expected, Buffer.from(hashPassword(password, stored.salt), 'hex'));
}


const escapeHtml = (s: string): string => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

function formPage(action: string, query: URLSearchParams, error: boolean): string {
  // Keycloak's `ui_locales`, sent by the engine with the page's language (chat step 5); the texts live in lang/<l>.json.
  const language: Language = query.get('ui_locales')?.startsWith('fr') ? 'fr' : 'en';
  const t = (key: string) => escapeHtml(text(language, `signin.${key}`));
  return `<!doctype html><html lang="${language}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${t('title')}</title>
<style>body{font:16px/1.5 system-ui,sans-serif;max-width:22rem;margin:3rem auto;padding:0 1rem}label{display:block;margin:.75rem 0 .25rem}input{width:100%;padding:.5rem;font:inherit;box-sizing:border-box}button{margin-top:1rem;padding:.6rem 1.2rem;font:inherit}.error{color:#b00020}.hint{color:#555;font-size:.85rem}.notice{background:#9a5b00;color:#fff;padding:.4rem .8rem;font-weight:600}</style></head>
<body><p class="notice">${t('notice')}</p><h1>${t('title')}</h1>
${error ? `<p class="error" role="alert">${t('error')}</p>` : ''}
<form method="post" action="${escapeHtml(`${action}?${query.toString()}`)}">
<label for="username">${t('account')}</label><input id="username" name="username" autocomplete="username" required autofocus>
<label for="password">${t('password')}</label><input id="password" name="password" type="password" autocomplete="current-password" required>
<button type="submit">${t('submit')}</button></form>
<p class="hint">${t('hint')}</p></body></html>\n`;
}

export async function startLocalSignIn(o: LocalSignInOptions): Promise<LocalSignIn> {
  const log = o.log ?? console.log;
  const audience = o.audience ?? 'eupadev-api';
  const issuerUrl = URL.canParse(o.issuer) ? new URL(o.issuer) : null;
  // Never beyond the loopback (ADR-028): the browser-facing URLs name this machine only.
  for (const [name, url] of [['OIDC_ISSUER', issuerUrl], ['OIDC_WEB_REDIRECT_URL', URL.canParse(o.redirectUrl) ? new URL(o.redirectUrl) : null]] as const) {
    if (url === null || !LOOPBACK_HOSTS.has(url.hostname.toLowerCase())) throw new Error(`${name}: a loopback URL (${[...LOOPBACK_HOSTS].join(', ')}) is expected by the local sign-in of the discovery mode`);
  }
  const realm = issuerUrl!.pathname.replace(/\/$/, '');
  const base = `${realm}/protocol/openid-connect`;
  const accounts = hashAccounts(o.passwords);
  const { publicKey, privateKey } = await generateKeyPair('ES256', { extractable: true });
  // ID tokens: RS256, Keycloak's default for a client (openid-client expects it); the engine trusts the access token only.
  const { privateKey: idTokenKey } = await generateKeyPair('RS256');
  const kid = `local-${randomBytes(4).toString('hex')}`;
  const jwk: JWK = { ...(await exportJWK(publicKey)), kid, use: 'sig', alg: 'ES256' };
  const codes = new Map<string, { account: string; nonce: string; challenge: string; redirectUri: string; clientId: string; expires: number }>();
  const readBody = async (req: http.IncomingMessage) => { let t = ''; for await (const m of req) { t += (m as Buffer).toString('utf8'); if (t.length > 16_384) throw new Error('body too large'); } return new URLSearchParams(t); };
  const accessToken = (account: string) => new SignJWT({
    email: `${account}@eupadev.invalid`, name: ACCOUNTS[account]!.name, preferred_username: account,
    resource_access: { [audience]: { roles: [...ACCOUNTS[account]!.roles] } },
  }).setProtectedHeader({ alg: 'ES256', kid, typ: 'at+jwt' }).setSubject(account).setIssuer(o.issuer).setAudience(audience).setIssuedAt().setExpirationTime(`${TOKEN_TTL_S}s`).sign(privateKey);
  /** The authorization request the engine builds (ADR-024): this client, its redirect URL, a code with PKCE S256. */
  const authRequestFault = (q: URLSearchParams): string | null => {
    if (q.get('client_id') !== o.clientId) return 'unknown client_id';
    if (q.get('redirect_uri') !== o.redirectUrl) return 'redirect_uri not registered';
    if (q.get('response_type') !== 'code') return 'response_type=code expected';
    if (q.get('code_challenge_method') !== 'S256' || !q.get('code_challenge')) return 'PKCE S256 required';
    if (!q.get('state')) return 'state required';
    return null;
  };
  const reply = (res: http.ServerResponse, status: number, type: string, body: string, headers: http.OutgoingHttpHeaders = {}) => {
    res.writeHead(status, { 'Content-Type': type, 'Cache-Control': 'no-store', 'X-Content-Type-Options': 'nosniff', 'Referrer-Policy': 'no-referrer', ...headers });
    res.end(body);
  };
  const page = (res: http.ServerResponse, status: number, html: string) => reply(res, status, 'text/html; charset=utf-8', html, { 'Content-Security-Policy': `default-src 'none'; style-src 'unsafe-inline'; form-action 'self' ${new URL(o.redirectUrl).origin}; frame-ancestors 'none'` });
  const json = (res: http.ServerResponse, status: number, body: unknown) => reply(res, status, 'application/json', JSON.stringify(body));

  const handle = async (req: http.IncomingMessage, res: http.ServerResponse): Promise<void> => {
    const url = new URL(req.url ?? '/', 'http://localhost');
    const q = url.searchParams;
    if (url.pathname === `${base}/certs` && req.method === 'GET') return json(res, 200, { keys: [jwk] });
    if (url.pathname === `${base}/auth` && (req.method === 'GET' || req.method === 'POST')) {
      const fault = authRequestFault(q);
      if (fault !== null) return reply(res, 400, 'text/plain; charset=utf-8', `authorization request refused: ${fault}\n`);
      if (req.method === 'GET') return page(res, 200, formPage(`${base}/auth`, q, false));
      const form = await readBody(req);
      const username = form.get('username') ?? '';
      if (!checkPassword(accounts, username, form.get('password') ?? '')) {
        log(`local sign-in: sign-in refused for "${username.slice(0, 40)}"`);
        return page(res, 401, formPage(`${base}/auth`, q, true));
      }
      for (const [c, v] of codes) if (v.expires < Date.now()) codes.delete(c);
      const code = randomBytes(16).toString('base64url');
      codes.set(code, { account: username, nonce: q.get('nonce') ?? '', challenge: q.get('code_challenge')!, redirectUri: o.redirectUrl, clientId: o.clientId, expires: Date.now() + CODE_TTL_MS });
      const back = new URL(o.redirectUrl);
      back.searchParams.set('code', code);
      back.searchParams.set('state', q.get('state')!);
      log(`local sign-in: ${username} signed in`);
      return reply(res, 303, 'text/plain; charset=utf-8', '', { Location: back.href });
    }
    if (url.pathname === `${base}/token` && req.method === 'POST') {
      const p = await readBody(req);
      const c = codes.get(p.get('code') ?? '');
      const challenge = createHash('sha256').update(p.get('code_verifier') ?? '').digest('base64url');
      const ok = c !== undefined && c.expires >= Date.now() && p.get('grant_type') === 'authorization_code' && p.get('redirect_uri') === c.redirectUri
        && challenge === c.challenge && p.get('client_id') === c.clientId && p.get('client_secret') === o.clientSecret;
      if (!ok) {
        log(`local sign-in: token request refused (code known: ${c !== undefined}, grant: ${p.get('grant_type')}, redirect_uri ok: ${p.get('redirect_uri') === c?.redirectUri}, pkce ok: ${challenge === c?.challenge}, client ok: ${p.get('client_id') === o.clientId && p.get('client_secret') === o.clientSecret})`);
        return json(res, 400, { error: 'invalid_grant' });
      }
      codes.delete(p.get('code')!);
      const idToken = await new SignJWT({ nonce: c.nonce, azp: c.clientId }).setProtectedHeader({ alg: 'RS256', kid: 'id-token-key' })
        .setSubject(c.account).setIssuer(o.issuer).setAudience(c.clientId).setIssuedAt().setExpirationTime(`${TOKEN_TTL_S}s`).sign(idTokenKey);
      return json(res, 200, { access_token: await accessToken(c.account), id_token: idToken, token_type: 'Bearer', expires_in: TOKEN_TTL_S });
    }
    if (url.pathname === `${base}/logout` && req.method === 'GET') {
      // No session of its own to end: straight back to the page, and only to it.
      const back = q.get('post_logout_redirect_uri') ?? '';
      if (!URL.canParse(back) || new URL(back).origin !== new URL(o.redirectUrl).origin) return reply(res, 400, 'text/plain; charset=utf-8', 'post_logout_redirect_uri: the page\'s origin only\n');
      return reply(res, 303, 'text/plain; charset=utf-8', '', { Location: back });
    }
    reply(res, 404, 'text/plain; charset=utf-8', `${req.method ?? '?'} ${url.pathname}: unknown route (${base}/auth, token, certs, logout)\n`);
  };
  const server = http.createServer((req, res) => {
    handle(req, res).catch((e: unknown) => {
      log(`local sign-in: ${req.method ?? '?'} ${req.url ?? '?'} failed: ${e instanceof Error ? e.message : String(e)}`);
      if (!res.headersSent) reply(res, 500, 'text/plain; charset=utf-8', 'internal error (see the local-signin log)\n');
    });
  }).listen(o.port ?? 8080, o.address ?? '127.0.0.1');
  await once(server, 'listening');
  const address = server.address() as AddressInfo;
  const url = `http://${address.family === 'IPv6' ? `[${address.address}]` : address.address}:${address.port}`;
  log(`local sign-in: listening on ${url}, issuer ${o.issuer}, realm path ${realm}`);
  return { url, jwksUrl: `${url}${base}/certs`, stop: () => new Promise((r) => server.close(() => r())) };
}

/** The container's entry: the engine's `OIDC_*` variables, the listen address and the two passwords from the installer. */
export function optionsFromEnv(env: Record<string, string | undefined>): LocalSignInOptions {
  const required = (name: string): string => {
    const v = env[name]?.trim() ?? '';
    if (v === '') throw new Error(`${name} missing`);
    return v;
  };
  const port = Number(env['API_PORT'] || 8080);
  if (!Number.isInteger(port) || port <= 0 || port > 65_535) throw new Error(`API_PORT invalid: "${env['API_PORT']}"`);
  return {
    issuer: required('OIDC_ISSUER'), clientId: required('OIDC_WEB_CLIENT_ID'), clientSecret: readSecret(env, 'OIDC_WEB_CLIENT_SECRET'), redirectUrl: required('OIDC_WEB_REDIRECT_URL'),
    audience: env['OIDC_AUDIENCE'] || 'eupadev-api', address: env['API_ADDRESS'] || '127.0.0.1', port,
    passwords: Object.fromEntries(Object.keys(ACCOUNTS).map((name) => [name, readSecret(env, passwordVariable(name))])),
  };
}

if (process.argv[1] !== undefined && import.meta.filename === process.argv[1]) {
  const signIn = await startLocalSignIn(optionsFromEnv(process.env));
  for (const signal of ['SIGTERM', 'SIGINT'] as const) process.once(signal, () => { void signIn.stop().then(() => process.exit(0)); });
}
