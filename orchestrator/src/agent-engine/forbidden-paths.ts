/**
 * Paths no agent modifies (analysis `docs/reflexions/2026-10-15-analyse-consignes-agents.md` §3.2-3.3, H2): pipelines, instructions,
 * Claude Code configuration, files that Git, pnpm or an editor executes or interprets, scanner exceptions, image build
 * (A-R0: the image comes from the platform's fixed `Dockerfile`, `.gitea/image/`, note
 * `docs/reflexions/2026-10-17-note-dockerfile-fixe.md`; `.pnpmfile.mjs` is executed by `pnpm prune` like `.pnpmfile.cjs`).
 * ONE single constant, three uses: the launcher refuses any bundle that touches them (`claude-engine.ts`, the guarantee);
 * `managed-settings.json` of the agent image refuses them to Edit/Write (belt and braces, generated by
 * `scripts/generate-claude-check.ts`); `gitea_protected_files` of the forge refuses them on push (belt and braces, copied
 * into `infra/ansible/group_vars/forge/vars.yml`, checked by `tests/forbidden-paths.test.ts`).
 * Forbidden at the root AND in any subfolder (a subfolder `.npmrc` acts on a pnpm workspace).
 * `vendor/` and `node_modules/` (G4, note `docs/reflexions/2026-10-20-note-socle-step-9.md`): dependencies, the core included, come from
 * the registry through the lockfile, never from files an agent writes.
 */
export const FORBIDDEN_DIRS = ['.claude', '.gitea', '.github', 'agents', '.opengrep', '.git', '.husky', '.vscode', '.idea', '.devcontainer', 'vendor', 'node_modules'] as const;
export const FORBIDDEN_FILES = [
  'AGENTS.md', 'AGENTS.fr.md', 'CLAUDE.md', 'CLAUDE.local.md', '.mcp.json', '.npmrc', '.pnpmfile.cjs', '.pnpmfile.mjs', 'pnpm-workspace.yaml',
  '.gitmodules', '.gitattributes', '.devcontainer.json', '.gitleaksignore', '.semgrepignore', '.trivyignore.yaml',
  'Dockerfile', '.dockerignore',
] as const;

/** True if the path (relative to the repository root, separator `/`) touches a forbidden folder or file. */
export function forbiddenPath(path: string): boolean {
  const segments = path.split('/');
  const dossiers = segments.slice(0, -1);
  const file = segments.at(-1) ?? '';
  return dossiers.some((d) => (FORBIDDEN_DIRS as readonly string[]).includes(d))
    || (FORBIDDEN_DIRS as readonly string[]).includes(file) // a file named like a forbidden folder (`.git` file = gitdir)
    || (FORBIDDEN_FILES as readonly string[]).includes(file);
}

/** `deny` rules of the managed settings: Edit also covers Write (permissions doc); two forms, root and subfolders ("two stars /" prefix). */
export function managedDenyRules(): string[] {
  return [
    ...FORBIDDEN_DIRS.flatMap((d) => [`Edit(${d}/**)`, `Edit(**/${d}/**)`]),
    ...FORBIDDEN_FILES.flatMap((f) => [`Edit(${f})`, `Edit(**/${f})`]),
    'Edit(//home/agent/.claude/**)', 'Edit(//etc/**)',
    'WebFetch', 'WebSearch', 'Agent',
  ];
}

/** Gitea `protected_file_patterns` (globs separated by `;`, two stars cross folders; the prefixed form does not include the root, hence both forms). */
export function giteaPatterns(): string {
  return [
    ...FORBIDDEN_DIRS.flatMap((d) => [`${d}/**`, `**/${d}/**`]),
    ...FORBIDDEN_FILES.flatMap((f) => [f, `**/${f}`]),
  ].join(';');
}
